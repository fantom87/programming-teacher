// Bundles the API server into ONE relocatable CommonJS file: build/server.cjs.
//
// Why: the desktop app ships to a machine with no repo, no node_modules and
// no Node install. Everything the server needs at runtime has to be either
// inside that one file or explicitly listed below as something the packager
// must copy alongside it.
//
// Run:  npm run bundle:server
//
// The bundle reads its content/docs/web-dist/data locations from PT_* env
// vars (see server/src/paths.ts) — nothing about the repo layout is baked in.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outfile = path.join(repoRoot, "build", "server.cjs");

// Packages that must NOT be inlined. Each entry is a runtime file lookup that
// bundling relocates and thereby breaks — verified by building and running,
// not by guessing. The packaging step has to ship each of these (with its own
// transitive deps) in a node_modules dir the bundle can resolve.
// Not exported on purpose: importing this module would run the build. The
// list is written to build/server.externals.json for the packaging step.
const EXTERNALS = [
  // Spawns its own `claude` CLI and resolves sibling files (cli.js, vendored
  // ripgrep, sdk tools) off its own package dir at runtime. Inlining it moves
  // those lookups into build/ and the tutor stops working.
  "@anthropic-ai/claude-agent-sdk",
  // Emscripten build: dist/sql-wasm.js reads dist/sql-wasm.wasm relative to
  // its own __dirname. Inlined, that becomes build/sql-wasm.wasm:
  //   failed to asynchronously prepare wasm: ENOENT .../build/sql-wasm.wasm
  // Every SQL lesson's local runner would fail.
  "sql.js",
  // Reads package data files off __dirname at require time:
  //   ENOENT: open '<drive>/browser/default-stylesheet.css'
  // plus a require.resolve("./xhr-sync-worker.js") that no longer resolves.
  // Loading jsdom at all would throw, killing every html-css dom check.
  "jsdom",
];

const result = await esbuild.build({
  entryPoints: [path.join(repoRoot, "server", "src", "index.ts")],
  outfile,
  bundle: true,
  platform: "node",
  target: "node22",
  format: "cjs",
  sourcemap: false,
  // Readability beats bytes here: when the desktop app misbehaves in the
  // field, the stack traces point into this file and someone has to read it.
  minify: false,
  external: EXTERNALS,
  // The sources are ESM: `import.meta.url` has no meaning in a CJS output and
  // esbuild would silently leave it empty (paths.ts would then resolve the
  // repo root from ""). Rewrite it to the CJS equivalent — the banner defines
  // the binding, so it means "this bundle's own file", exactly as the ESM
  // original meant "this module's own file".
  define: {
    "import.meta.url": "__ptImportMetaUrl",
    "import.meta.dirname": "__dirname",
    "import.meta.filename": "__filename",
  },
  banner: {
    js: [
      "// Generated by scripts/bundle-server.mjs — do not edit. Run `npm run bundle:server`.",
      'const __ptImportMetaUrl = require("node:url").pathToFileURL(__filename).href;',
    ].join("\n"),
  },
  logLevel: "info",
  metafile: true,
});

const bytes = fs.statSync(outfile).size;
const inlined = Object.keys(result.metafile.inputs).filter((f) => f.includes("node_modules"));
const packages = new Set(
  inlined.map((f) => {
    const rest = f.slice(f.lastIndexOf("node_modules/") + "node_modules/".length);
    const parts = rest.split("/");
    return parts[0].startsWith("@") ? `${parts[0]}/${parts[1]}` : parts[0];
  }),
);

// Machine-readable contract for the packaging step, so the list of packages
// it must ship can never drift from the list this build actually externalised.
const manifest = path.join(repoRoot, "build", "server.externals.json");
fs.writeFileSync(manifest, `${JSON.stringify({ entry: "server.cjs", externals: EXTERNALS }, null, 2)}\n`);

console.log(`\n[bundle] ${path.relative(repoRoot, outfile)} — ${(bytes / 1024 / 1024).toFixed(2)} MB`);
console.log(`[bundle] inlined ${packages.size} package(s) from node_modules`);
console.log(`[bundle] EXTERNAL (ship these, with their transitive deps, in a resolvable node_modules):`);
for (const e of EXTERNALS) console.log(`           ${e}`);
console.log(`[bundle] wrote ${path.relative(repoRoot, manifest)}`);
